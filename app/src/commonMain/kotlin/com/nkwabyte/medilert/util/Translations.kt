val LocalAppLanguage = staticCompositionLocalOf { "English" }

@Composable
@ReadOnlyComposable
fun String.tr(): String {
    val currentLanguage = LocalAppLanguage.current
    if (currentLanguage == "English") {
        return this
    }
    
    // Check if Akan (Twi) is selected
    if (currentLanguage.contains("Akan", ignoreCase = true) || currentLanguage.contains("Twi", ignoreCase = true)) {
        return TwiTranslations.map[this] ?: this
    }
    
    return this
}

